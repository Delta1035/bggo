export function stylesheet(
  imageUri: string,
  opacity: number,
  blur: number,
  position: string,
): string {
  return `/* Generated by BGGo Wallpaper. */
body::after {
  content: "";
  position: fixed;
  inset: -${blur * 2}px;
  z-index: 1001;
  pointer-events: none;
  background-image: url("${imageUri}");
  background-position: ${position};
  background-repeat: no-repeat;
  background-size: cover;
  opacity: ${opacity};
  filter: blur(${blur}px);
}
`;
}

export function cleanPatches(html: string): string {
  // 1. 清理 BGGo 本身的注入
  const bggoRegex = new RegExp(`${BGGO_START_TAG}[\\s\\S]*?${BGGO_END_TAG}\\n*`, "g");
  let next = html.replace(bggoRegex, "");

  // 2. 清理旧版 custom-css 注入的 BGGo 脚本以及 session-id、indicator
  next = next.replace(
    /<!-- !! VSCODE-CUSTOM-CSS-START !! -->[\s\S]*?<!-- !! VSCODE-CUSTOM-CSS-END !! -->\n*/g,
    "",
  );
  next = next.replace(/<!-- !! VSCODE-CUSTOM-CSS-SESSION-ID [\w-]+ !! -->\n*/g, "");
  next = next.replace(
    /<script>\/\* eslint-env browser \*\/[\s\S]*?__CUSTOM_CSS_JS_INDICATOR_CLS[\s\S]*?<\/script>\n*/g,
    "",
  );

  return next;
}

export function ensureCSP(html: string): string {
  if (/<meta\s+http-equiv=["']Content-Security-Policy["']/i.test(html)) {
    return html;
  }
  if (/<meta\s+charset=[^>]+>/i.test(html)) {
    return html.replace(/(<meta\s+charset=[^>]+>)/i, `$1\n\t\t${DEFAULT_CSP}`);
  }
  return html.replace(/<head>/i, `<head>\n\t\t${DEFAULT_CSP}`);
}

export function patchHTMLContent(html: string, cssContent: string): string {
  let cleaned = cleanPatches(html);
  cleaned = ensureCSP(cleaned);

  const styleBlock = `${BGGO_START_TAG}\n<style id="bggo-wallpaper-style">\n${cssContent}</style>\n${BGGO_END_TAG}\n`;
  if (cleaned.includes("</head>")) {
    return cleaned.replace("</head>", `${styleBlock}</head>`);
  }
  return `${cleaned}\n${styleBlock}`;
}

export function unpatchHTMLContent(html: string): string {
  let cleaned = cleanPatches(html);
  cleaned = ensureCSP(cleaned);
  return cleaned;
}

export async function locateWorkbench(appRoot?: string): Promise<WorkbenchTarget | undefined> {
  const root = appRoot ?? getVSCodeAppRoot();
  if (!root) {
    return undefined;
  }
  const realAppRoot = await fs.realpath(root);
  const base = path.join(realAppRoot, "out", "vs", "code");
  const directories = [
    path.join(base, "electron-browser", "workbench"),
    path.join(base, "electron-browser"),
    path.join(base, "electron-sandbox", "workbench"),
    path.join(base, "electron-sandbox"),
  ];
  const htmlNames = [
    "workbench-dev.html",
    "workbench.esm.html",
    "workbench.html",
    "workbench-apc-extension.html",
  ];

  for (const directory of directories) {
    for (const htmlName of htmlNames) {
      const html = path.join(directory, htmlName);
      try {
        if (!(await fs.stat(html)).isFile()) {
          continue;
        }
        const realDirectory = await fs.realpath(directory);
        const realHTML = await fs.realpath(html);
        return {
          directory: realDirectory,
          html: realHTML,
        };
      } catch {
        // Try next candidate
      }
    }
  }
  return undefined;
}

function getVSCodeAppRoot(): string | undefined {
  try {
    // 动态获取，避免在无 vscode 运行时的测试环境中报错
    // eslint-disable-next-line @typescript-eslint/no-require-imports
    const vscode = require("vscode");
    return vscode.env?.appRoot;
  } catch {
    return undefined;
  }
}

export async function applyWorkbenchPatch(cssContent: string, appRoot?: string): Promise<boolean> {
  const target = await locateWorkbench(appRoot);
  if (!target) {
    throw new Error("未能定位 VS Code 工作台入口文件");
  }

  const rawHTML = await fs.readFile(target.html, "utf8");
  const backupPath = path.join(target.directory, "workbench.bggo-backup.html");

  try {
    await fs.access(backupPath);
  } catch {
    // 首次运行时备份当前文件
    await fs.writeFile(backupPath, rawHTML, "utf8");
  }

  const patched = patchHTMLContent(rawHTML, cssContent);
  if (patched !== rawHTML) {
    await fs.writeFile(target.html, patched, "utf8");
  }
  return true;
}

export async function removeWorkbenchPatch(appRoot?: string): Promise<boolean> {
  const target = await locateWorkbench(appRoot);
  if (!target) {
    return false;
  }

  try {
    const rawHTML = await fs.readFile(target.html, "utf8");
    const cleaned = unpatchHTMLContent(rawHTML);
    if (cleaned !== rawHTML) {
      await fs.writeFile(target.html, cleaned, "utf8");
    }
    return true;
  } catch {
    return false;
  }
}
